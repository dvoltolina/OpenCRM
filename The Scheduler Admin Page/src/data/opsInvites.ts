/**
 * Ops Invites Data Layer
 * Owner invites created by ops (super-admin only).
 */

import {
  getDocs,
  addDoc,
  query,
  where,
  orderBy,
  serverTimestamp,
} from 'firebase/firestore';

import { opsInvitesCollection } from './opsFirestoreBase';
import { logOpsAuditEvent } from './opsAuditLog';
import type { OpsOwnerInvite } from '../types/ops';

/**
 * List all owner invites for a tenant.
 */
export async function listOpsInvites(businessId: string): Promise<OpsOwnerInvite[]> {
  const ref = opsInvitesCollection();
  const q = query(
    ref,
    where('businessId', '==', businessId),
    orderBy('createdAt', 'desc'),
  );
  const snap = await getDocs(q);

  return snap.docs.map((d) => {
    const data = d.data() as Record<string, unknown>;
    const createdTs = data.createdAt as { toDate?: () => Date } | undefined;
    return {
      ...data,
      id: d.id,
      createdAt: createdTs?.toDate?.()?.toISOString() ?? new Date().toISOString(),
    } as OpsOwnerInvite;
  });
}

/**
 * Create a new owner invite for a tenant.
 * Invite expires in 7 days.
 */
export async function createOwnerInvite(
  businessId: string,
  email: string,
  operatorId: string,
  operatorEmail: string,
): Promise<string> {
  const ref = opsInvitesCollection();

  const expiresAt = new Date();
  expiresAt.setDate(expiresAt.getDate() + 7); // 7-day expiry

  // Note: id is auto-generated by Firestore
  const docRef = await addDoc(ref, {
    businessId,
    email,
    createdBy: operatorId,
    createdAt: serverTimestamp(),
    expiresAt: expiresAt.toISOString(),
    status: 'pending',
  } as unknown as OpsOwnerInvite);

  await logOpsAuditEvent({
    operatorId,
    operatorEmail,
    action: 'owner_invite_created',
    businessId,
    metadata: { inviteEmail: email, expiresAt: expiresAt.toISOString() },
  });

  return docRef.id;
}
