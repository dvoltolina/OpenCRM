/**
 * Ops Audit Logging
 * Audit trail for all ops actions (super-admin only).
 * Logs are immutable - no update/delete allowed.
 */

import { addDoc, serverTimestamp, getDocs, query, orderBy, limit, where } from 'firebase/firestore';

import { isDemoMode } from '../config/demo';
import { opsAuditCollection } from './opsFirestoreBase';
import type { OpsAuditAction, OpsAuditLog } from '../types/ops';

export type OpsAuditInput = {
  operatorId: string;
  operatorEmail: string;
  action: OpsAuditAction;
  businessId: string;
  businessName?: string;
  metadata?: Record<string, unknown>;
};

/**
 * Log an ops audit event. Best-effort: never blocks primary action.
 */
export async function logOpsAuditEvent(input: OpsAuditInput): Promise<void> {
  if (isDemoMode) {
    return;
  }
  try {
    // Sanitize metadata - truncate long strings, limit array sizes
    const sanitizedMetadata = input.metadata
      ? sanitizeMetadata(input.metadata)
      : undefined;

    // Note: id and timestamp are auto-generated by Firestore
    await addDoc(opsAuditCollection(), {
      operatorId: input.operatorId,
      operatorEmail: input.operatorEmail,
      action: input.action,
      businessId: input.businessId,
      businessName: input.businessName,
      metadata: sanitizedMetadata,
      timestamp: serverTimestamp(),
    } as unknown as OpsAuditLog);
  } catch (error) {
    // Best-effort: never block primary action
    console.warn('[ops-audit] Failed to write ops audit log', input.action, error);
  }
}

/**
 * Fetch recent ops audit logs (most recent first).
 */
export async function listOpsAuditLogs(maxResults = 100): Promise<OpsAuditLog[]> {
  if (isDemoMode) {
    return [];
  }
  const ref = opsAuditCollection();
  const q = query(ref, orderBy('timestamp', 'desc'), limit(maxResults));
  const snap = await getDocs(q);
  return snap.docs.map((d) => {
    const data = d.data() as Record<string, unknown>;
    const ts = data.timestamp as { toDate?: () => Date } | undefined;
    return {
      ...data,
      id: d.id,
      // Convert Firestore timestamp to ISO string
      timestamp: ts?.toDate?.()?.toISOString() ?? new Date().toISOString(),
    } as OpsAuditLog;
  });
}

/**
 * Fetch ops audit logs for a specific tenant.
 */
export async function listOpsAuditLogsForTenant(
  businessId: string,
  maxResults = 50,
): Promise<OpsAuditLog[]> {
  if (isDemoMode) {
    return [];
  }
  const ref = opsAuditCollection();
  const q = query(
    ref,
    where('businessId', '==', businessId),
    orderBy('timestamp', 'desc'),
    limit(maxResults),
  );
  const snap = await getDocs(q);
  return snap.docs.map((d) => {
    const data = d.data() as Record<string, unknown>;
    const ts = data.timestamp as { toDate?: () => Date } | undefined;
    return {
      ...data,
      id: d.id,
      timestamp: ts?.toDate?.()?.toISOString() ?? new Date().toISOString(),
    } as OpsAuditLog;
  });
}

/**
 * Sanitize metadata for audit logging.
 */
function sanitizeMetadata(
  obj: Record<string, unknown>,
  maxStringLength = 200,
  maxArraySize = 10,
): Record<string, unknown> {
  const result: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === 'string') {
      result[key] = value.length > maxStringLength
        ? value.slice(0, maxStringLength) + '...'
        : value;
    } else if (Array.isArray(value)) {
      result[key] = value.slice(0, maxArraySize);
    } else if (value && typeof value === 'object') {
      result[key] = sanitizeMetadata(value as Record<string, unknown>);
    } else {
      result[key] = value;
    }
  }

  return result;
}
