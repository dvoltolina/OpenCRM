/**
 * Ops Notes Data Layer
 * Support notes per tenant (super-admin only).
 */

import {
  getDocs,
  addDoc,
  query,
  orderBy,
  serverTimestamp,
} from 'firebase/firestore';

import { opsNotesCollection } from './opsFirestoreBase';
import { logOpsAuditEvent } from './opsAuditLog';
import type { OpsNote, OpsNoteInput, OpsNoteCategory, OpsNotePriority } from '../types/ops';

/**
 * List all ops notes for a tenant.
 */
export async function listOpsNotes(businessId: string): Promise<OpsNote[]> {
  const ref = opsNotesCollection(businessId);
  const q = query(ref, orderBy('createdAt', 'desc'));
  const snap = await getDocs(q);

  return snap.docs.map((d) => {
    const data = d.data() as Record<string, unknown>;
    const createdTs = data.createdAt as { toDate?: () => Date } | undefined;
    const updatedTs = data.updatedAt as { toDate?: () => Date } | undefined;
    return {
      ...data,
      id: d.id,
      // Convert Firestore timestamp to ISO string
      createdAt: createdTs?.toDate?.()?.toISOString() ?? new Date().toISOString(),
      updatedAt: updatedTs?.toDate?.()?.toISOString(),
    } as OpsNote;
  });
}

/**
 * Add a support note for a tenant.
 */
export async function addOpsNote(
  businessId: string,
  input: {
    content: string;
    createdBy: string;
    createdByEmail: string;
    category?: OpsNoteCategory;
    priority?: OpsNotePriority;
  },
): Promise<string> {
  const ref = opsNotesCollection(businessId);

  // Note: id is auto-generated by Firestore
  const docRef = await addDoc(ref, {
    businessId,
    content: input.content,
    createdBy: input.createdBy,
    createdByEmail: input.createdByEmail,
    category: input.category ?? 'general',
    priority: input.priority ?? 'normal',
    createdAt: serverTimestamp(),
  } as unknown as OpsNote);

  await logOpsAuditEvent({
    operatorId: input.createdBy,
    operatorEmail: input.createdByEmail,
    action: 'note_added',
    businessId,
    metadata: {
      category: input.category ?? 'general',
      priority: input.priority ?? 'normal',
      contentPreview: input.content.slice(0, 100),
    },
  });

  return docRef.id;
}
