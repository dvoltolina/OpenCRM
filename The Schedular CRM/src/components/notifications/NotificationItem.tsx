// ============================================
// Helper Functions
// ============================================

/**
 * Format relative time for display
 */
function formatTimeAgo(date: Date): string {
  const now = new Date();
  const diffMs = now.getTime() - date.getTime();
  const diffMins = Math.floor(diffMs / (1000 * 60));
  const diffHours = Math.floor(diffMs / (1000 * 60 * 60));
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));

  if (diffMins < 1) return 'Just now';
  if (diffMins < 60) return `${diffMins}m ago`;
  if (diffHours < 24) return `${diffHours}h ago`;
  if (diffDays === 1) return 'Yesterday';
  if (diffDays < 7) return `${diffDays}d ago`;

  return date.toLocaleDateString('en-US', {
    month: 'short',
    day: 'numeric',
  });
}

/**
 * Get CSS class for priority
 */
function getPriorityClass(priority: string): string {
  switch (priority) {
    case 'urgent':
      return 'notification-priority-urgent';
    case 'high':
      return 'notification-priority-high';
    case 'low':
      return 'notification-priority-low';
    default:
      return '';
  }
}

// ============================================
// Component
// ============================================

export function NotificationItem({
  notification,
  onMarkRead,
  onArchive,
  onNavigate,
}: NotificationItemProps) {
  const navigate = useNavigate();
  const iconType = notification.iconType || getIconTypeForNotification(notification.type);

  const handleClick = () => {
    // Mark as read
    if (!notification.isRead && onMarkRead) {
      onMarkRead(notification.id);
    }

    // Navigate to action URL
    if (notification.actionUrl) {
      onNavigate?.();
      navigate(notification.actionUrl);
    }
  };

  const handleMarkRead = (e: React.MouseEvent) => {
    e.stopPropagation();
    onMarkRead?.(notification.id);
  };

  const handleArchive = (e: React.MouseEvent) => {
    e.stopPropagation();
    onArchive?.(notification.id);
  };

  return (
    <div
      className={`notification-item ${!notification.isRead ? 'notification-item-unread' : ''} ${getPriorityClass(notification.priority)}`}
      onClick={handleClick}
      role="button"
      tabIndex={0}
      onKeyDown={(e) => e.key === 'Enter' && handleClick()}
    >
      {!notification.isRead && <div className="notification-unread-dot" />}

      <div className="notification-item-icon">
        {getNotificationIcon(iconType)}
      </div>

      <div className="notification-item-content">
        <div className="notification-item-header">
          <h4 className="notification-item-title">{notification.title}</h4>
          <span className="notification-item-time">
            {formatTimeAgo(notification.createdAt)}
          </span>
        </div>

        <p className="notification-item-body">{notification.body}</p>

        {notification.actorName && (
          <span className="notification-item-actor">
            by {notification.actorName}
          </span>
        )}
      </div>

      <div className="notification-item-actions">
        {!notification.isRead && (
          <button
            className="notification-action-btn notification-action-read"
            onClick={handleMarkRead}
            title="Mark as read"
          >
            <svg fill="none" stroke="currentColor" viewBox="0 0 24 24">
              <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 13l4 4L19 7" />
            </svg>
          </button>
        )}
        <button
          className="notification-action-btn notification-action-archive"
          onClick={handleArchive}
          title="Archive"
        >
          <svg fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M5 8h14M5 8a2 2 0 110-4h14a2 2 0 110 4M5 8v10a2 2 0 002 2h10a2 2 0 002-2V8m-9 4h4" />
          </svg>
        </button>
      </div>
    </div>
  );
}
